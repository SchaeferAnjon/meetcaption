/** 这种语言的固定字；没有手写的给英文的（own: false，要模型自己换成那种语言）。 */
export function templateWords(lang) {
  const own = Object.hasOwn(WORDS, lang)
  return { ...(own ? WORDS[lang] : WORDS.en), own }
}

/** 接在 Markdown 模板的要求后面：模板已经是这种语言的就照抄；英文代写的让模型把固定的字都换成那种语言。 */
export function templateRule(lang) {
  if (lang === 'zh') return ''
  const L = promptLang(lang)
  if (templateWords(lang).own) return `\n- 下面结构里的小节标题、表头和「${WORDS[lang].quote.trim()}」这些固定的字已经是${L}，照着写，整份都用${L}，不要夹${lang === 'zh-Hant' ? '简体字' : '中文'}。待办的截止日期写成 YYYY-MM-DD。`
  return `\n- 下面的结构是用英语写的：小节标题、表头和 None、Quote:、Due:、(to be confirmed) 这些固定的字都换成${L}，整份都用${L}，不要留英语和中文的固定字。待办的截止日期照样写成 YYYY-MM-DD。`
}

const escapeRe = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')

/** 课堂笔记里程序要认的小节标题（i 是 class 里的下标），各语言的都认；中文的照旧只看关键字。 */
export function classHeadRe(i) {
  const zh = { 0: '概览|概覽', 1: '大纲|知识点|大綱|知識點', 7: '自测|自測' }[i]
  return new RegExp([zh, ...Object.values(WORDS).map((w) => escapeRe(w.class[i]))].filter(Boolean).join('|'), 'i')
}

/** 自测题答案前面的「答案：」，各语言的都认。 */
export const ANSWER_WORDS = [...new Set(Object.values(WORDS).map((w) => w.answer.replace(/\s*[：:]\s*$/, '')))]
